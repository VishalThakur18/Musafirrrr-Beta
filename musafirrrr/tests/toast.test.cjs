const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const state = { toasts: [] }, timers = new Map();
let sequence = 0;
const context = vm.createContext({ store: { quiet: fn => fn(state) }, setTimeout: fn => { timers.set(++sequence, fn); return sequence; }, clearTimeout: id => timers.delete(id) });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../src/middleware/toast.js'), 'utf8'), context);
context.toast('First');
const oldCallback = [...timers.values()][0];
context.toast('Second', 'bad');
assert.equal(state.toasts.length, 1);
assert.equal(state.toasts[0].msg, 'Second');
assert.equal(state.toasts[0].kind, 'bad');
assert.equal(timers.size, 1);
oldCallback();
assert.equal(state.toasts[0].msg, 'Second', 'Old timeout cannot remove replacement');
[...timers.values()][0]();
assert.equal(state.toasts.length, 0);
console.log('PASS: newest toast replaces older toast, resets timeout and survives stale timeout callbacks.');
