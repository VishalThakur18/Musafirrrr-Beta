const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
let reference = { current: null }, cleanup, nextId = 0;
const events = [], listeners = new Set();
const doc = { visibilityState: 'visible', addEventListener: (_, fn) => listeners.add(fn), removeEventListener: (_, fn) => listeners.delete(fn) };
const context = vm.createContext({ useRef: () => reference, useEffect: effect => { cleanup?.(); cleanup = effect(); }, document: doc, crypto: { randomUUID: () => String(++nextId) }, events });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../src/features/organizerDashboard/services/analytics.service.js'), 'utf8') + '\ntripAnalytics.track = (trip, kind, id) => events.push({tripId:trip.id,kind,id});', context);
const trip = { id: 'trip-a', fromDb: true };
context.useTripEnquiryOpen(trip, false); assert.equal(events.length, 0);
context.useTripEnquiryOpen(trip, true); assert.equal(events.length, 1);
context.useTripEnquiryOpen({ ...trip }, true); assert.equal(events.length, 1, 'Rerenders do not count again');
doc.visibilityState = 'hidden'; listeners.forEach(fn => fn()); doc.visibilityState = 'visible'; listeners.forEach(fn => fn()); assert.equal(events.length, 1);
context.useTripEnquiryOpen(trip, false); assert.equal(listeners.size, 0);
context.useTripEnquiryOpen(trip, true); assert.equal(events.length, 2);
assert.notEqual(events[0].id, events[1].id, 'Reopening has a new event ID');
context.useTripEnquiryOpen(trip, false); doc.visibilityState = 'hidden';
context.useTripEnquiryOpen(trip, true); assert.equal(events.length, 2);
context.useTripEnquiryOpen(trip, false); doc.visibilityState = 'visible'; listeners.forEach(fn => fn()); assert.equal(events.length, 2, 'Unseen modal is not counted');
context.useTripEnquiryOpen({ id: 'trip-b', fromDb: false }, true); assert.equal(events.length, 2);
context.useTripEnquiryOpen({ id: 'trip-b', fromDb: true }, true); assert.equal(events.length, 3, 'Counts after real trip data arrives');
assert.equal(events[2].tripId, 'trip-b');
assert.ok(events.every(event => event.kind === 'enquiry_open'));
cleanup?.(); assert.equal(listeners.size, 0);
console.log('PASS: actual visible opens only, rerender deduplication, reopening IDs, hidden-modal exclusion, real-trip readiness and listener cleanup.');
